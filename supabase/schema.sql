-- Pedido: pendente não tem pagamento; confirmado/finalizado precisa de data de pagamento.
create or replace function public.regras_pedido() returns trigger language plpgsql as $$
begin
  if new.status = 'PENDENTE_PAGAMENTO' then
    new.data_pagamento := null;
    new.forma_pagamento := 'NAO_REALIZADO';
  elsif new.status in ('CONFIRMADO','FINALIZADO') and new.data_pagamento is null then
    new.data_pagamento := (now() at time zone 'America/Sao_Paulo');
  end if;
  if tg_op = 'INSERT' and new.status = 'CANCELADO' then
    raise exception 'Não é possível criar um pedido já cancelado.';
  end if;
  if tg_op = 'INSERT' and new.usuario_id is null then
    new.usuario_id := auth.uid();
  end if;
  return new;
end $$;
create trigger pedido_regras before insert or update on public.pedido
  for each row execute function public.regras_pedido();

-- Item: preço e custo vêm do produto (preço informado só vale para produto com preço 0, ex.: bolo de festa).
create or replace function public.regras_item_pedido() returns trigger language plpgsql as $$
declare p public.produto;
begin
  select * into p from public.produto where id = new.produto_id;
  if not found then raise exception 'Produto % não encontrado.', new.produto_id; end if;
  if tg_op = 'INSERT' or new.produto_id is distinct from old.produto_id then
    new.preco_unitario := case when p.preco_final = 0 then coalesce(new.preco_unitario, 0) else p.preco_final end;
    new.custo_producao := p.custo_producao;
  end if;
  return new;
end $$;
create trigger item_pedido_regras before insert or update on public.item_pedido
  for each row execute function public.regras_item_pedido();

-- Custo de uma receita = soma de (custo por medida × quantidade), como no Java.
create or replace function public.custo_receita(p_receita int) returns numeric language sql stable as $$
  select round(coalesce(sum(i.custo_medida * ri.quantidade), 0), 2)
    from public.receita_ingrediente ri join public.ingrediente i on i.id = ri.ingrediente_id
   where ri.receita_id = p_receita
$$;

-- ---------------------------------------------------------------------
-- Papéis e regras de acesso (RLS)
--   ATENDENTE+     : clientes, pedidos, itens, detalhamentos, produtos
--   GERENTE+       : ingredientes, categorias, receitas, tipos de receita
--   ADMINISTRADOR  : funcionários, convites e dashboards
--   Todos da equipe leem o catálogo.
-- ---------------------------------------------------------------------
create or replace function public.minha_funcao() returns text
language sql stable security definer set search_path = public as $$
  select funcao from public.perfis where id = auth.uid()
$$;
create or replace function public.e_equipe()  returns boolean language sql stable as $$ select public.minha_funcao() is not null $$;
create or replace function public.e_gerente() returns boolean language sql stable as $$ select coalesce(public.minha_funcao() in ('GERENTE','ADMINISTRADOR'), false) $$;
create or replace function public.e_admin()   returns boolean language sql stable as $$ select coalesce(public.minha_funcao() = 'ADMINISTRADOR', false) $$;

-- Novo login: cria o perfil; a função vem do convite (nunca do que a pessoa digitou).
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare c public.convites;
begin
  select * into c from public.convites where lower(email) = lower(new.email);
  insert into public.perfis (id, nome, cpf, email, telefone, funcao)
  values (new.id,
          coalesce(c.nome, nullif(new.raw_user_meta_data->>'nome',''), split_part(new.email,'@',1)),
          c.cpf, new.email, c.telefone, c.funcao)
  on conflict (id) do nothing;
  if c.email is not null then delete from public.convites where email = c.email; end if;
  return new;
exception when others then
  raise warning 'Anjos Bolos: perfil não criado: %', sqlerrm;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

