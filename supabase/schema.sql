  data_pedido      timestamp not null default (now() at time zone 'America/Sao_Paulo'),
  data_retirada    timestamp,
  data_pagamento   timestamp,
  forma_pagamento  text not null default 'NAO_REALIZADO' check (forma_pagamento in (
    'DINHEIRO','CARTAO_CREDITO','CARTAO_DEBITO','VOUCHER','PIX','NAO_REALIZADO')),
