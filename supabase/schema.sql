create table public.categoria_produto (
  id         int generated by default as identity primary key,
  nome       text not null unique,
  descricao  text not null default ''
);

create table public.produto (
  id               int generated by default as identity primary key,
  nome             text not null unique,
  preco_final      numeric(10,2) not null default 0 check (preco_final >= 0),
  custo_producao   numeric(10,2) not null default 0 check (custo_producao >= 0),
  categoria_id     int references public.categoria_produto(id) on delete set null,
  imagem_path      text
);

create table public.tipo_receita (
  id         int generated by default as identity primary key,
  nome       text not null unique,
  descricao  text not null default ''
);

create table public.receita (
  id               int generated by default as identity primary key,
  nome             text not null,
  tipo_receita_id  int references public.tipo_receita(id) on delete set null
);

create table public.receita_ingrediente (
  receita_id      int not null references public.receita(id) on delete cascade,
  ingrediente_id  int not null references public.ingrediente(id) on delete restrict,
  quantidade      numeric(12,3) not null check (quantidade > 0),
  unidade_medida  text not null check (unidade_medida in (
    'UNIDADE','GRAMA','QUILOGRAMA','LITRO','MILILITRO','XICARA_CHA','COLHER_SOPA',
    'COLHER_CHA','COLHER_CAFE','COLHER_SOBREMESA','PITADA','COPO_AMERICANO')),
  primary key (receita_id, ingrediente_id)
);

create table public.composicao_produto (
  produto_id  int not null references public.produto(id) on delete cascade,
  receita_id  int not null references public.receita(id) on delete cascade,
  quantidade  numeric(12,3) not null default 1,
  observacao  text,
  primary key (produto_id, receita_id)
);

