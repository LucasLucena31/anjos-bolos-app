create or replace function public.exigir_admin() returns void language plpgsql stable as $$
begin
  if not public.e_admin() then raise exception 'Apenas administradores veem os dashboards.' using errcode = '42501'; end if;
end $$;

create or replace function public.dash_margem_lucro(p_maior boolean)
returns table (nome_produto text, margem_lucro numeric) language plpgsql stable as $$
begin
  perform public.exigir_admin();
  return query
    select p.nome, round((p.preco_final - p.custo_producao) / p.preco_final * 100, 2)
      from public.produto p where p.preco_final > 0
     order by case when p_maior then -((p.preco_final - p.custo_producao) / p.preco_final)
                   else  ((p.preco_final - p.custo_producao) / p.preco_final) end
     limit 1;
end $$;

create or replace function public.dash_produtos_mais_vendidos(p_inicio date, p_fim date, p_limite int default 5)
returns table (nome_produto text, quantidade_vendida numeric, categoria_produto text) language plpgsql stable as $$
begin
  perform public.exigir_admin();
  return query
    select p.nome, sum(ip.quantidade), c.nome
      from public.pedido pd
      join public.item_pedido ip on ip.pedido_id = pd.id
      join public.produto p on p.id = ip.produto_id
      left join public.categoria_produto c on c.id = p.categoria_id
     where pd.status = 'FINALIZADO' and pd.data_pedido >= p_inicio and pd.data_pedido < p_fim + 1
     group by p.id, p.nome, c.nome
     order by sum(ip.quantidade) desc
     limit p_limite;
end $$;

create or replace function public.dash_pedidos_faturamento(p_inicio date, p_fim date)
returns table (quantidade_pedidos bigint, quantidade_produtos_vendidos numeric, faturamento numeric, custos numeric, data_pedido date)
language plpgsql stable as $$
begin
  perform public.exigir_admin();
  return query
    select count(distinct pd.id), sum(ip.quantidade),
           round(sum(ip.preco_unitario * ip.quantidade), 2), round(sum(ip.custo_producao * ip.quantidade), 2),
           coalesce(pd.data_retirada, pd.data_pedido)::date
      from public.pedido pd join public.item_pedido ip on ip.pedido_id = pd.id
     where pd.status = 'FINALIZADO' and pd.data_pedido >= p_inicio and pd.data_pedido < p_fim + 1
     group by coalesce(pd.data_retirada, pd.data_pedido)::date
     order by 5;
end $$;

create or replace function public.dash_vendas_dia_semana(p_inicio date, p_fim date)
returns table (dia_semana text, total_vendas bigint) language plpgsql stable as $$
begin
  perform public.exigir_admin();
  return query
    select (array['Segunda-feira','Terça-feira','Quarta-feira','Quinta-feira','Sexta-feira','Sábado','Domingo'])[extract(isodow from pd.data_pedido)::int],
           count(*)
      from public.pedido pd
     where pd.status = 'FINALIZADO' and pd.data_pedido >= p_inicio and pd.data_pedido < p_fim + 1
     group by extract(isodow from pd.data_pedido)
     order by extract(isodow from pd.data_pedido);
end $$;

-- Feriados nacionais calculados aqui mesmo (antes vinham de um JSON no S3).
create or replace function public.pascoa(p_ano int) returns date language plpgsql immutable as $$
declare a int; b int; c int; d int; e int; f int; g int; h int; i int; k int; l int; m int; mes int; dia int;
begin
  a := p_ano % 19; b := p_ano / 100; c := p_ano % 100; d := b / 4; e := b % 4;
  f := (b + 8) / 25; g := (b - f + 1) / 3; h := (19 * a + b - d - g + 15) % 30;
  i := c / 4; k := c % 4; l := (32 + 2 * e + 2 * i - h - k) % 7; m := (a + 11 * h + 22 * l) / 451;
  mes := (h + l - 7 * m + 114) / 31; dia := ((h + l - 7 * m + 114) % 31) + 1;
  return make_date(p_ano, mes, dia);
end $$;

create or replace function public.feriados_nacionais(p_ano int)
returns table (data date, nome text) language sql immutable as $$
  select * from (values
    (make_date(p_ano,1,1),   'Confraternização Universal'),
    (public.pascoa(p_ano) - 47, 'Carnaval'),
    (public.pascoa(p_ano) - 2,  'Sexta-feira Santa'),
    (public.pascoa(p_ano),      'Páscoa'),
    (make_date(p_ano,4,21),  'Tiradentes'),
    (make_date(p_ano,5,1),   'Dia do Trabalho'),
    (public.pascoa(p_ano) + 60, 'Corpus Christi'),
    (make_date(p_ano,9,7),   'Independência do Brasil'),
    (make_date(p_ano,10,12), 'Nossa Senhora Aparecida'),
    (make_date(p_ano,11,2),  'Finados'),
    (make_date(p_ano,11,15), 'Proclamação da República'),
    (make_date(p_ano,11,20), 'Dia Nacional de Zumbi e da Consciência Negra'),
    (make_date(p_ano,12,25), 'Natal')
  ) f(data, nome) order by 1
$$;

-- Para os 3 próximos feriados: o produto mais vendido de cada categoria
-- na semana que antecedeu o mesmo feriado no ano anterior.
create or replace function public.dash_produtos_recomendados_feriados()
returns table (data_feriado date, feriado text, produto text, categoria text) language plpgsql stable as $$
declare
  hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  f record;
begin
  perform public.exigir_admin();
  for f in
    select x.data, x.nome from (
      select * from public.feriados_nacionais(extract(year from hoje)::int)
      union all select * from public.feriados_nacionais(extract(year from hoje)::int + 1)) x
    where x.data > hoje order by x.data limit 3
  loop
    return query
      select f.data, f.nome, t.produto, t.categoria from (
        select distinct on (c.id) p.nome as produto, c.nome as categoria, sum(ip.quantidade) as qtd
          from public.pedido pd
          join public.item_pedido ip on ip.pedido_id = pd.id
          join public.produto p on p.id = ip.produto_id
          join public.categoria_produto c on c.id = p.categoria_id
         where pd.status = 'FINALIZADO'
           and pd.data_pedido >= (f.data - interval '1 year' - interval '7 days')
           and pd.data_pedido <  (f.data - interval '1 year' + interval '1 day')
         group by c.id, p.id, p.nome, c.nome
         order by c.id, sum(ip.quantidade) desc) t;
  end loop;
end $$;

