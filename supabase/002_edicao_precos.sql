-- Histórico de preços dos produtos
create table if not exists public.produto_historico_preco (
  id                    int generated by default as identity primary key,
  produto_id            int not null references public.produto(id) on delete cascade,
  preco_anterior        numeric(10,2),
  preco_novo            numeric(10,2),
  custo_anterior        numeric(10,2),
  custo_novo            numeric(10,2),
  alterado_por          uuid references public.perfis(id) on delete set null,
  alterado_em           timestamptz not null default now()
);

create or replace function public.registrar_preco_produto() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.preco_final is distinct from old.preco_final or new.custo_producao is distinct from old.custo_producao then
    insert into public.produto_historico_preco (produto_id, preco_anterior, preco_novo, custo_anterior, custo_novo, alterado_por)
    values (new.id, old.preco_final, new.preco_final, old.custo_producao, new.custo_producao, auth.uid());
  end if;
  return new;
end $$;
drop trigger if exists produto_historico on public.produto;
create trigger produto_historico after update on public.produto
  for each row execute function public.registrar_preco_produto();

-- Histórico de custos dos ingredientes
create table if not exists public.ingrediente_historico_custo (
  id              int generated by default as identity primary key,
  ingrediente_id  int not null references public.ingrediente(id) on delete cascade,
  custo_anterior  numeric(16,10),
  custo_novo      numeric(16,10),
  alterado_por    uuid references public.perfis(id) on delete set null,
  alterado_em     timestamptz not null default now()
);

create or replace function public.registrar_custo_ingrediente() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.custo_medida is distinct from old.custo_medida then
    insert into public.ingrediente_historico_custo (ingrediente_id, custo_anterior, custo_novo, alterado_por)
    values (new.id, old.custo_medida, new.custo_medida, auth.uid());
  end if;
  return new;
end $$;
drop trigger if exists ingrediente_historico on public.ingrediente;
create trigger ingrediente_historico after update on public.ingrediente
  for each row execute function public.registrar_custo_ingrediente();

-- A equipe consulta o histórico; ninguém edita (só os gatilhos acima gravam).
alter table public.produto_historico_preco     enable row level security;
alter table public.ingrediente_historico_custo enable row level security;
drop policy if exists "historico produto: equipe lê" on public.produto_historico_preco;
create policy "historico produto: equipe lê" on public.produto_historico_preco for select to authenticated using (public.e_equipe());
drop policy if exists "historico ingrediente: equipe lê" on public.ingrediente_historico_custo;
create policy "historico ingrediente: equipe lê" on public.ingrediente_historico_custo for select to authenticated using (public.e_equipe());
